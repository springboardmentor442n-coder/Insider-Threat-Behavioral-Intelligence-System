def _get_live_investigation_records() -> list[dict[str, Any]]:
    """
    Get the current investigation cases.

    The investigation service currently maintains the application's
    investigation state. We read it at report-generation time so
    status/assignment/notes changes are reflected.
    """
    try:
        cases = get_all_cases()
    except Exception:
        return []

    if not cases:
        return []

    generated_at = _utc_now()

    records: list[dict[str, Any]] = []

    for case in cases:
        if not isinstance(case, dict):
            continue

        evidence = case.get("evidence", [])

        if isinstance(evidence, list):
            evidence_text = ", ".join(
                str(item)
                for item in evidence
            )
        else:
            evidence_text = str(
                evidence or ""
            )

        records.append(
            {
                "generated_at": generated_at,
                "case_id": case.get("id"),
                "employee": case.get("employee"),
                "department": case.get("department"),
                "risk_score": case.get("risk_score"),
                "risk_level": case.get("risk_level"),
                "prediction": case.get("prediction"),
                "status": case.get("status"),
                "assigned_to": case.get("assigned_to"),
                "created_at": case.get("created_at"),
                "last_updated": case.get("last_updated"),
                "evidence": evidence_text,
                "notes": case.get("notes"),
            }
        )

    records.sort(
        key=lambda item: -float(
            item.get("risk_score")
            or 0
        )
    )

    return records


