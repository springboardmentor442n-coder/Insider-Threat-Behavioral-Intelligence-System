def _utc_now() -> str:
    return "2011-05-31 00:00:00 UTC"


def _normalise_report_name(report_name: str) -> str:
    """
    Normalise a report identifier for matching.
    """
    return str(report_name or "").strip().lower()


def _report_identifier(report_name: str, path: Path | None = None) -> str:
    """
    Build a combined identifier from report name and filename.
    """
    name_part = _normalise_report_name(report_name)

    path_part = ""
    if path is not None:
        path_part = _normalise_report_name(path.name)

    return f"{name_part} {path_part}".strip()


def _is_investigation_report(
    report_name: str,
    path: Path | None = None,
) -> bool:
    """
    Determine whether a configured report represents investigations/cases.
    """
    identifier = _report_identifier(report_name, path)

    return any(
        keyword in identifier
        for keyword in INVESTIGATION_KEYWORDS
    )


def _is_live_risk_report(
    report_name: str,
    path: Path | None = None,
) -> bool:
    """
    Determine whether a report should be generated from live
    ML/risk/threat data.
    """
    identifier = _report_identifier(report_name, path)

    return any(
        keyword in identifier
        for keyword in LIVE_REPORT_KEYWORDS
    )


def _safe_value(value: Any) -> Any:
    """
    Convert values into CSV-safe primitive values.
    """
    if value is None:
        return ""

    if isinstance(value, (list, tuple, set)):
        return ", ".join(
            str(item)
            for item in value
        )

    if isinstance(value, dict):
        return str(value)

    return value


def _records_from_path(path: Path) -> list[dict[str, Any]]:
    """
    Safely read an existing CSV report.

    This is retained for reports that are still intentionally
    generated by the existing offline pipeline.
    """
    if not path.exists():
        return []

    try:
        df = load_csv(path)
    except Exception:
        return []

    if df is None or df.empty:
        return []

    records = df.to_dict(orient="records")

    return [
        {
            key: _safe_value(value)
            for key, value in record.items()
        }
        for record in records
    ]


