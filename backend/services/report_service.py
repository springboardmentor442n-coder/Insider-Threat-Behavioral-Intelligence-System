def _get_combined_investigation_report() -> list[dict[str, Any]]:
    """
    Combine investigation information with the canonical live
    Threat Center risk data where employee identity can be matched.

    This gives downloaded reports more useful information than the
    old static CSV-only implementation.
    """
    threats = _get_live_threat_records()
    investigations = _get_live_investigation_records()

    threat_by_user: dict[str, dict[str, Any]] = {}

    for threat in threats:
        user = str(
            threat.get("user")
            or ""
        ).strip().lower()

        if user:
            threat_by_user[user] = threat

    records: list[dict[str, Any]] = []

    for investigation in investigations:
        employee = str(
            investigation.get("employee")
            or ""
        ).strip()

        employee_key = employee.lower()

        matching_threat = threat_by_user.get(
            employee_key
        )

        # If the investigation employee is a CERT user ID,
        # we can directly match it.
        #
        # For demonstration cases such as John Carter,
        # there may be no CERT user ID yet. In that case
        # we preserve the investigation record instead of
        # fabricating an identity.
        live_risk = matching_threat or {}

        records.append(
            {
                "generated_at": investigation.get(
                    "generated_at"
                ),

                "case_id": investigation.get(
                    "case_id"
                ),

                "employee": employee,

                "user": live_risk.get(
                    "user",
                    "",
                ),

                "department": investigation.get(
                    "department"
                ),

                "risk_score": (
                    live_risk.get(
                        "risk_score"
                    )
                    if live_risk
                    else investigation.get(
                        "risk_score"
                    )
                ),

                "risk_level": (
                    live_risk.get(
                        "risk_level"
                    )
                    if live_risk
                    else investigation.get(
                        "risk_level"
                    )
                ),

                "prediction": investigation.get(
                    "prediction"
                ),

                "threat_type": live_risk.get(
                    "threat_type",
                    "",
                ),

                "status": investigation.get(
                    "status"
                ),

                "assigned_to": investigation.get(
                    "assigned_to"
                ),

                "created_at": investigation.get(
                    "created_at"
                ),

                "last_updated": investigation.get(
                    "last_updated"
                ),

                "evidence": investigation.get(
                    "evidence"
                ),

                "notes": investigation.get(
                    "notes"
                ),

                "models_triggered": live_risk.get(
                    "models_triggered",
                    "",
                ),

                "suspicious_count": live_risk.get(
                    "suspicious_count",
                    "",
                ),

                "consensus_percentage": live_risk.get(
                    "consensus_percentage",
                    "",
                ),

                "weighted_score": live_risk.get(
                    "weighted_score",
                    "",
                ),
            }
        )

    return records


