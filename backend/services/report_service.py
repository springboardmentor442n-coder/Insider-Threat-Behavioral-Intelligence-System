"""
Reports Service

Live report generation for the Insider Threat Behavioral Intelligence System.

IMPORTANT
---------
Reports must not blindly depend on stale pre-generated CSV files.

The canonical runtime flow is:

    ML Employee Intelligence
            ↓
    Threat / Risk Data
            ↓
    Investigation Data
            ↓
    Report Generation
            ↓
    CSV Download

Existing configured report files are preserved for compatibility.

For risk/threat/investigation reports, the service refreshes the
report from the current runtime data before returning/downloading it.
"""

